import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
  homes: defineTable({
    token: v.string(),
    name: v.string(),
    city: v.string(),
    moveDate: v.string(),
    budget: v.number(),
    createdAt: v.number(),
    inboxId: v.optional(v.string()),
    demo: v.boolean(),
  }).index("by_token", ["token"]),
  tasks: defineTable({
    homeId: v.id("homes"),
    room: v.string(),
    title: v.string(),
    done: v.boolean(),
    cost: v.number(),
    assignee: v.string(),
    priority: v.string(),
    note: v.string(),
    order: v.number(),
  }).index("by_home", ["homeId"]),
  sources: defineTable({
    homeId: v.id("homes"),
    title: v.string(),
    url: v.string(),
    summary: v.string(),
    category: v.string(),
    capturedAt: v.number(),
    status: v.string(),
  }).index("by_home", ["homeId"]),
  messages: defineTable({
    homeId: v.id("homes"),
    subject: v.string(),
    body: v.string(),
    recipient: v.string(),
    status: v.string(),
    createdAt: v.number(),
    providerId: v.optional(v.string()),
    error: v.optional(v.string()),
  }).index("by_home", ["homeId"]),
  activity: defineTable({
    homeId: v.id("homes"),
    text: v.string(),
    createdAt: v.number(),
  }).index("by_home", ["homeId"]),
  jobs: defineTable({
    homeId: v.id("homes"),
    type: v.string(),
    status: v.string(),
    createdAt: v.number(),
    input: v.optional(v.string()),
    messageId: v.optional(v.id("messages")),
    result: v.optional(v.string()),
    error: v.optional(v.string()),
  }).index("by_home", ["homeId"]),
  rateLimits: defineTable({
    key: v.string(),
    window: v.number(),
    count: v.number(),
  }).index("by_key", ["key"]),
});
